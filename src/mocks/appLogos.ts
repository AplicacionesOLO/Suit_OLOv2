function normalizeKey(s: string): string {
  return s
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/\s+/g, '')
    .replace(/-+/g, '')
    .replace(/_+/g, '');
}

export function findAppLogo(appName?: string, appCode?: string): { light: string; dark: string } | null {
  if (!appName && !appCode) return null;

  // Exact name match
  if (appName && appLogoMap[appName]) return appLogoMap[appName];

  // Exact code match
  if (appCode && appLogoMap[appCode]) return appLogoMap[appCode];

  // Normalized match by name
  if (appName) {
    const normalizedName = normalizeKey(appName);
    for (const [key, value] of Object.entries(appLogoMap)) {
      if (normalizeKey(key) === normalizedName) return value;
    }
  }

  // Normalized match by code
  if (appCode) {
    const normalizedCode = normalizeKey(appCode);
    for (const [key, value] of Object.entries(appLogoMap)) {
      if (normalizeKey(key) === normalizedCode) return value;
    }
  }

  return null;
}